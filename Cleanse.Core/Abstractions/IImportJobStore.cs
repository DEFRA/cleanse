using Cleanse.Core.Domain.Imports;

namespace Cleanse.Core.Abstractions;

public interface IImportJobStore
{
    Task<ImportJob?> GetAsync(Guid id, CancellationToken cancellationToken = default);

    /// <summary>
    /// Fails when the group already has a pending or processing job. Relational providers back
    /// this with a unique partial index, so two concurrent uploads cannot both win.
    /// </summary>
    Task<bool> TryCreateAsync(ImportJob job, CancellationToken cancellationToken = default);

    Task SaveAsync(ImportJob job, CancellationToken cancellationToken = default);

    Task<ImportJob?> GetActiveForGroupAsync(string groupId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Atomically moves one pending job to processing and returns it. Returns null when there is
    /// nothing to do, so several workers can poll without duplicating work.
    /// </summary>
    Task<ImportJob?> LeaseNextPendingAsync(DateTimeOffset now, CancellationToken cancellationToken = default);

    /// <summary>Processing jobs whose worker has stopped reporting.</summary>
    Task<IReadOnlyList<ImportJob>> FindStalledAsync(
        DateTimeOffset olderThan,
        int limit,
        CancellationToken cancellationToken = default);

    Task<PagedResult<ImportJob>> SearchAsync(
        string? groupId,
        PageRequest page,
        CancellationToken cancellationToken = default);

    Task AddRejectionsAsync(
        IReadOnlyCollection<ImportJobRejection> rejections,
        CancellationToken cancellationToken = default);

    Task<PagedResult<ImportJobRejection>> GetRejectionsAsync(
        Guid importJobId,
        PageRequest page,
        CancellationToken cancellationToken = default);
}

/// <summary>
/// Where uploaded extracts live. A local directory in development, an S3 bucket on CDP. Keys are
/// always generated by the service, never taken from the uploaded filename.
/// </summary>
public interface IImportFileStore
{
    Task WriteAsync(string key, Stream content, CancellationToken cancellationToken = default);

    Task<Stream> OpenReadAsync(string key, CancellationToken cancellationToken = default);

    Task<bool> ExistsAsync(string key, CancellationToken cancellationToken = default);
}
